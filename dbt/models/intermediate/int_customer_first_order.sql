-- First and latest order per customer; the cohort is the IST month of the first order.
SELECT
    CUSTOMER_ID,
    MIN(PLACED_TS_IST) AS FIRST_ORDER_AT_IST,
    MAX(PLACED_TS_IST) AS LAST_ORDER_AT_IST,
    DATE_TRUNC('month', MIN(PLACED_DATE_IST)) AS COHORT_MONTH,
    COUNT(*) AS LIFETIME_ORDERS,
    COUNT_IF(ORDER_STATUS = 'DELIVERED') AS LIFETIME_DELIVERED_ORDERS,
    SUM(IFF(ORDER_STATUS = 'DELIVERED', TOTAL_INR, 0)) AS LIFETIME_GMV_INR
FROM {{ ref('stg_orders') }}
GROUP BY CUSTOMER_ID
