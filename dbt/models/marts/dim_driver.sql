-- Drivers seen on orders. Home zone = the zone they delivered to most often.
SELECT
    DRIVER_ID,
    MODE(ZONE_ID) AS MAIN_ZONE_ID,
    MIN(DRIVER_ASSIGNED_TS) AS FIRST_ASSIGNED_AT,
    MAX(DRIVER_ASSIGNED_TS) AS LAST_ASSIGNED_AT,
    COUNT(*) AS ORDERS_ASSIGNED,
    COUNT_IF(ORDER_STATUS = 'DELIVERED') AS ORDERS_DELIVERED
FROM {{ ref('stg_orders') }}
WHERE DRIVER_ID IS NOT NULL
GROUP BY DRIVER_ID
