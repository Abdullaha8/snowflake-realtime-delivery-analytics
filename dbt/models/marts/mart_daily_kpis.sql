-- Daily KPIs per zone (IST days). GMV counts delivered orders only; AOV = GMV / delivered.
SELECT
    F.PLACED_DATE_IST AS DATE_DAY,
    F.ZONE_ID,
    D.IS_WEEKEND,
    COUNT(*) AS ORDERS_PLACED,
    COUNT_IF(F.IS_DELIVERED) AS ORDERS_DELIVERED,
    COUNT_IF(F.IS_CANCELLED) AS ORDERS_CANCELLED,
    COUNT_IF(F.SLA_BREACHED) AS SLA_BREACHES,
    COUNT_IF(F.IS_RAINING) AS ORDERS_IN_RAIN,
    COUNT(DISTINCT F.CUSTOMER_ID) AS ACTIVE_CUSTOMERS,
    SUM(F.GMV_INR) AS GMV_INR,
    ROUND(SUM(F.GMV_INR) / NULLIF(COUNT_IF(F.IS_DELIVERED), 0), 2) AS AOV_INR,
    ROUND(100 * COUNT_IF(F.IS_DELIVERED) / COUNT(*), 2) AS DELIVERED_PCT,
    ROUND(100 * COUNT_IF(F.IS_CANCELLED) / COUNT(*), 2) AS CANCELLED_PCT,
    ROUND(100 * COUNT_IF(F.SLA_BREACHED) / NULLIF(COUNT_IF(F.IS_DELIVERED), 0), 2) AS SLA_BREACH_PCT,
    ROUND(AVG(F.ACTUAL_DELIVERY_MIN), 2) AS AVG_DELIVERY_MIN,
    SUM(F.SURGE_FEE_INR) AS SURGE_FEES_INR,
    SUM(F.DISCOUNT_INR) AS DISCOUNTS_INR
FROM {{ ref('fct_orders') }} AS F
INNER JOIN {{ ref('dim_date') }} AS D ON F.PLACED_DATE_IST = D.DATE_DAY
GROUP BY 1, 2, 3
