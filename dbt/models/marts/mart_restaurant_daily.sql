-- Kitchen performance per restaurant and IST day: prep time vs estimate, rejects, cancellations.
SELECT
    F.PLACED_DATE_IST AS DATE_DAY,
    F.RESTAURANT_ID,
    R.RESTAURANT_NAME,
    R.CUISINE,
    R.ZONE_ID,
    COUNT(*) AS ORDERS_PLACED,
    COUNT_IF(F.ACCEPTED_TS IS NOT NULL) AS ORDERS_ACCEPTED,
    COUNT_IF(F.CANCEL_REASON IN ('RESTAURANT_REJECTED', 'ITEM_UNAVAILABLE')) AS RESTAURANT_REJECTS,
    COUNT_IF(F.IS_CANCELLED) AS ORDERS_CANCELLED,
    COUNT_IF(F.IS_DELIVERED) AS ORDERS_DELIVERED,
    ROUND(100 * COUNT_IF(F.CANCEL_REASON IN ('RESTAURANT_REJECTED', 'ITEM_UNAVAILABLE')) / COUNT(*), 2)
        AS REJECT_PCT,
    ROUND(AVG(F.ESTIMATED_PREP_MIN), 2) AS AVG_ESTIMATED_PREP_MIN,
    ROUND(AVG(F.ACTUAL_PREP_MIN), 2) AS AVG_ACTUAL_PREP_MIN,
    ROUND(APPROX_PERCENTILE(F.ACTUAL_PREP_MIN, 0.9), 2) AS P90_ACTUAL_PREP_MIN,
    ROUND(AVG(F.PREP_DELAY_MIN), 2) AS AVG_PREP_DELAY_MIN,
    COUNT_IF(F.SLA_BREACHED) AS SLA_BREACHES,
    SUM(F.GMV_INR) AS GMV_INR
FROM {{ ref('fct_orders') }} AS F
LEFT JOIN {{ ref('dim_restaurant') }} AS R ON F.RESTAURANT_ID = R.RESTAURANT_ID AND R.IS_CURRENT
GROUP BY 1, 2, 3, 4, 5
