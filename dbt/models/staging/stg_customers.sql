-- Customer signups. Contains PII (name, email, phone): masked in P7.
SELECT
    ENTITY_ID AS CUSTOMER_ID,
    EVENT_TS AS SIGNED_UP_AT,
    CONVERT_TIMEZONE('UTC', 'Asia/Kolkata', EVENT_TS) AS SIGNED_UP_AT_IST,
    PAYLOAD:full_name::STRING AS FULL_NAME,
    PAYLOAD:email::STRING AS EMAIL,
    PAYLOAD:phone::STRING AS PHONE,
    PAYLOAD:zone_id::STRING AS HOME_ZONE_ID,
    PAYLOAD:h3_r8::STRING AS HOME_H3_R8,
    PAYLOAD:signup_channel::STRING AS SIGNUP_CHANNEL
FROM {{ source('silver', 'REFERENCE_EVENTS') }}
WHERE EVENT_TYPE = 'CUSTOMER_REGISTERED'
QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_TS) = 1
