"""Write airflow/.env from the repo .env - only what Airflow needs, nothing else.

Airflow gets the Snowflake connection for the SVC_AIRFLOW service user (key file mounted
read-only by airflow/docker-compose.override.yml). The Kafka connector's key and your personal
admin key never reach the Airflow containers.

python scripts/gen_airflow_env.py
"""

from __future__ import annotations

import json
import os
import sys

from _env import ROOT, load_dotenv

KEY_IN_CONTAINER = "/usr/local/airflow/secrets/airflow_rsa_key.p8"
REQUIRED = ("SNOWFLAKE_ACCOUNT", "SNOWFLAKE_DATABASE", "SNOWFLAKE_AIRFLOW_USER")


def render(env: dict[str, str]) -> str:
    conn = {
        "conn_type": "snowflake",
        "login": env["SNOWFLAKE_AIRFLOW_USER"],
        "schema": "OPS",
        "extra": {
            "account": env["SNOWFLAKE_ACCOUNT"],
            "database": env["SNOWFLAKE_DATABASE"],
            "warehouse": "WH_TRANSFORM",
            "role": "FOODDEL_TRANSFORM",
            "private_key_file": KEY_IN_CONTAINER,
            # attributes pipeline compute to "airflow" in the cost report
            "session_parameters": {"QUERY_TAG": "airflow"},
        },
    }
    lines = [
        "# Generated by scripts/gen_airflow_env.py from ../.env - do not edit, do not commit.",
        f"AIRFLOW_CONN_SNOWFLAKE_DEFAULT={json.dumps(conn, separators=(',', ':'))}",
        f"SNOWFLAKE_ACCOUNT={env['SNOWFLAKE_ACCOUNT']}",
        f"SNOWFLAKE_DATABASE={env['SNOWFLAKE_DATABASE']}",
        f"SNOWFLAKE_AIRFLOW_USER={env['SNOWFLAKE_AIRFLOW_USER']}",
        f"SNOWFLAKE_AIRFLOW_PRIVATE_KEY_PATH={KEY_IN_CONTAINER}",
        "AIRFLOW__CORE__LOAD_EXAMPLES=False",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    load_dotenv()
    missing = [k for k in REQUIRED if not os.environ.get(k)]
    if missing:
        print(f"missing in .env: {', '.join(missing)}")
        return 1
    if not (ROOT / "secrets" / "airflow_rsa_key.p8").exists():
        print("secrets/airflow_rsa_key.p8 missing: run `make sf-keygen`")
        return 1
    out = ROOT / "airflow" / ".env"
    out.write_text(render({k: os.environ[k] for k in REQUIRED}), encoding="utf-8", newline="\n")
    print(
        f"wrote {out.relative_to(ROOT)} (Snowflake connection for {os.environ['SNOWFLAKE_AIRFLOW_USER']})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
