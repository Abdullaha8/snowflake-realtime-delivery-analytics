-- 01_setup.sql: database, schemas, warehouses and resource monitors.
-- Run as ACCOUNTADMIN via `make sf-setup`. Idempotent: CREATE ... IF NOT EXISTS, then ALTER to
-- re-apply settings that may have drifted (IF NOT EXISTS alone would not fix a resized warehouse).

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS ${SNOWFLAKE_DATABASE}
COMMENT = 'Real-time food delivery analytics (Pune)';

CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.BRONZE
COMMENT = 'Raw events exactly as landed from Kafka / backfill (VARIANT)';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.SILVER
COMMENT = 'Deduplicated, typed events (Dynamic Tables)';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.GOLD
COMMENT = 'Real-time aggregates: SLA, demand/supply, surge (Dynamic Tables)';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.MARTS
COMMENT = 'Historical star schema (dbt)';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.STAGING
COMMENT = 'dbt staging/intermediate models and snapshots (not exposed to BI)';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.OPS
COMMENT = 'Pipeline operations: runs, data-quality results, latency metrics, alerts';
CREATE SCHEMA IF NOT EXISTS ${SNOWFLAKE_DATABASE}.ML
COMMENT = 'ETA model: feature table, Model Registry models, predictions, accuracy';

-- Warehouses: XSMALL, suspend after 60 s idle, created suspended so setup costs nothing.
-- Snowpipe Streaming ingestion is serverless and does not use a warehouse at all.
CREATE WAREHOUSE IF NOT EXISTS WH_INGEST WITH
WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
COMMENT = 'Backfill COPY and ingestion checks';
ALTER WAREHOUSE WH_INGEST SET WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS WH_TRANSFORM WITH
WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
COMMENT = 'Dynamic Tables refresh and dbt';
ALTER WAREHOUSE WH_TRANSFORM SET WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS WH_BI WITH
WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
COMMENT = 'Dashboards and ad-hoc queries';
ALTER WAREHOUSE WH_BI SET WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

-- Resource monitors (ACCOUNTADMIN only). They cap *warehouse* credits; serverless features
-- (Snowpipe Streaming, Dynamic Table storage) are not covered and are watched separately.
-- IF NOT EXISTS + ALTER instead of CREATE OR REPLACE: replacing would reset used credits.
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_FOODDEL_ACCOUNT WITH
CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
TRIGGERS ON 75 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER RESOURCE MONITOR RM_FOODDEL_ACCOUNT SET CREDIT_QUOTA = 20;
ALTER ACCOUNT SET RESOURCE_MONITOR = RM_FOODDEL_ACCOUNT;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_WH_INGEST WITH
CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER RESOURCE MONITOR RM_WH_INGEST SET CREDIT_QUOTA = 5;
ALTER WAREHOUSE WH_INGEST SET RESOURCE_MONITOR = RM_WH_INGEST;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_WH_TRANSFORM WITH
CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER RESOURCE MONITOR RM_WH_TRANSFORM SET CREDIT_QUOTA = 5;
ALTER WAREHOUSE WH_TRANSFORM SET RESOURCE_MONITOR = RM_WH_TRANSFORM;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_WH_BI WITH
CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND ON 110 PERCENT DO SUSPEND_IMMEDIATE;
ALTER RESOURCE MONITOR RM_WH_BI SET CREDIT_QUOTA = 5;
ALTER WAREHOUSE WH_BI SET RESOURCE_MONITOR = RM_WH_BI;
