-- 02_rbac.sql: functional roles, the Kafka connector service user, least-privilege grants.
-- Run via `make sf-setup`. Grants use ALL + FUTURE so this script works before or after the
-- tables in 03_bronze.sql exist.
--
--   FOODDEL_INGEST     Kafka connector: write BRONZE, nothing else
--   FOODDEL_TRANSFORM  Dynamic Tables / dbt: read BRONZE, build SILVER, GOLD, MARTS
--   FOODDEL_BI         dashboards: read GOLD and MARTS
-- All roll up to SYSADMIN so administrators keep control of objects these roles create.

USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS FOODDEL_INGEST COMMENT = 'Kafka connector: insert into BRONZE only';
CREATE ROLE IF NOT EXISTS FOODDEL_TRANSFORM COMMENT = 'Read BRONZE; build SILVER/GOLD/MARTS';
CREATE ROLE IF NOT EXISTS FOODDEL_BI COMMENT = 'Read GOLD and MARTS';

-- TYPE = SERVICE: cannot log in with a password or through the UI; key-pair only.
CREATE USER IF NOT EXISTS SVC_KAFKA_CONNECTOR
    TYPE = SERVICE
    DEFAULT_ROLE = FOODDEL_INGEST
    COMMENT = 'Snowflake Connector for Kafka (key-pair auth)';
ALTER USER SVC_KAFKA_CONNECTOR SET RSA_PUBLIC_KEY = '${SNOWFLAKE_CONNECTOR_PUBLIC_KEY}';

-- Airflow runs the batch pipeline (DT refresh, dbt, data quality) as its own service user.
CREATE USER IF NOT EXISTS SVC_AIRFLOW
    TYPE = SERVICE
    DEFAULT_ROLE = FOODDEL_TRANSFORM
    DEFAULT_WAREHOUSE = WH_TRANSFORM
    COMMENT = 'Airflow orchestration (key-pair auth)';
ALTER USER SVC_AIRFLOW SET RSA_PUBLIC_KEY = '${SNOWFLAKE_AIRFLOW_PUBLIC_KEY}';

USE ROLE SECURITYADMIN;

GRANT ROLE FOODDEL_INGEST TO ROLE SYSADMIN;
GRANT ROLE FOODDEL_TRANSFORM TO ROLE SYSADMIN;
GRANT ROLE FOODDEL_BI TO ROLE SYSADMIN;

GRANT ROLE FOODDEL_INGEST TO USER SVC_KAFKA_CONNECTOR;
GRANT ROLE FOODDEL_TRANSFORM TO USER SVC_AIRFLOW;
GRANT ROLE FOODDEL_TRANSFORM TO USER ${SNOWFLAKE_ADMIN_USER};
GRANT ROLE FOODDEL_BI TO USER ${SNOWFLAKE_ADMIN_USER};

-- INGEST: exactly what the v4 connector docs require for pre-created tables in default pipe
-- mode (INSERT on the table; CREATE PIPE on the schema for the connector-managed pipe).
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_INGEST;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_INGEST;
GRANT CREATE PIPE ON SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_INGEST;
GRANT INSERT ON ALL TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_INGEST;
GRANT INSERT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_INGEST;

-- TRANSFORM
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_TRANSFORM;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_TRANSFORM;
GRANT SELECT ON ALL TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_TRANSFORM;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.BRONZE TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE TABLE, CREATE VIEW, CREATE DYNAMIC TABLE
ON SCHEMA ${SNOWFLAKE_DATABASE}.SILVER TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE TABLE, CREATE VIEW, CREATE DYNAMIC TABLE
ON SCHEMA ${SNOWFLAKE_DATABASE}.GOLD TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE TABLE, CREATE VIEW, CREATE DYNAMIC TABLE
ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ${SNOWFLAKE_DATABASE}.STAGING TO ROLE FOODDEL_TRANSFORM;
GRANT USAGE ON WAREHOUSE WH_TRANSFORM TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE TABLE, CREATE VIEW, CREATE PROCEDURE
ON SCHEMA ${SNOWFLAKE_DATABASE}.OPS TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE ALERT ON SCHEMA ${SNOWFLAKE_DATABASE}.OPS TO ROLE FOODDEL_TRANSFORM; -- noqa: PRS
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE MODEL ON SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_TRANSFORM; -- noqa: PRS
GRANT CREATE ALERT ON SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_TRANSFORM; -- noqa: PRS

-- BI
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_BI;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.GOLD TO ROLE FOODDEL_BI;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.GOLD TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${SNOWFLAKE_DATABASE}.GOLD TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.GOLD TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS TO ROLE FOODDEL_BI;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE FOODDEL_BI;

-- OPS is readable by BI (pipeline health dashboards in P8).
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.OPS TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.OPS TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${SNOWFLAKE_DATABASE}.OPS TO ROLE FOODDEL_BI;

-- ML: BI reads predictions and accuracy (P8 dashboards).
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_BI;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ${SNOWFLAKE_DATABASE}.ML TO ROLE FOODDEL_BI;

-- Alerts (P5): account-level privileges only ACCOUNTADMIN can grant. Serverless alerts also
-- need EXECUTE MANAGED ALERT.
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE ALERT ON ACCOUNT TO ROLE FOODDEL_TRANSFORM;
GRANT EXECUTE MANAGED ALERT ON ACCOUNT TO ROLE FOODDEL_TRANSFORM;
