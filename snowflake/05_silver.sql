-- 05_silver.sql: SILVER Dynamic Tables - deduplicated, typed events and one row per order.
-- Run via `make sf-dt`. Owned by FOODDEL_TRANSFORM, refreshed on WH_TRANSFORM.
--
-- TARGET_LAG = DOWNSTREAM: SILVER refreshes only when a GOLD table needs it, so it never
-- costs more than GOLD's lag. REFRESH_MODE = INCREMENTAL is explicit: if a query ever uses a
-- construct that cannot refresh incrementally, CREATE fails instead of silently falling back
-- to (expensive) full refreshes.
--
-- Late and out-of-order events need no special handling: every refresh folds newly arrived
-- BRONZE rows into the result, so an event that is 6 hours late still updates its order.

USE ROLE FOODDEL_TRANSFORM;
USE WAREHOUSE WH_TRANSFORM;
USE SCHEMA ${SNOWFLAKE_DATABASE}.SILVER;

-- Order lifecycle events, one row per event_id (injected duplicates removed).
CREATE OR REPLACE DYNAMIC TABLE ORDER_EVENTS
TARGET_LAG = DOWNSTREAM
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Deduplicated order lifecycle events (first-arrived copy per event_id)'
AS
SELECT
    RECORD_CONTENT:event_id::STRING AS EVENT_ID,
    RECORD_CONTENT:event_type::STRING AS EVENT_TYPE,
    RECORD_CONTENT:data:order_id::STRING AS ORDER_ID,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:event_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EVENT_TS,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:emitted_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EMITTED_TS,
    DATEDIFF('millisecond', EVENT_TS, EMITTED_TS) / 1000 AS LATENESS_S,
    RECORD_CONTENT:source::STRING AS EVENT_SOURCE,
    RECORD_CONTENT:data AS PAYLOAD,
    COALESCE(RECORD_METADATA:source::STRING, 'kafka') AS LOAD_SOURCE,
    RECORD_METADATA:partition::NUMBER AS KAFKA_PARTITION,
    RECORD_METADATA:offset::NUMBER AS KAFKA_OFFSET
FROM ${SNOWFLAKE_DATABASE}.BRONZE.ORDERS_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY EVENT_ID
    ORDER BY EMITTED_TS, KAFKA_PARTITION, KAFKA_OFFSET, RECORD_METADATA:file_row::NUMBER
) = 1;

-- Driver GPS pings, deduplicated. H3 is recomputed in Snowflake and compared with the
-- simulator's cell (H3_MATCH) as a geo data-quality check.
CREATE OR REPLACE DYNAMIC TABLE DRIVER_PINGS
TARGET_LAG = DOWNSTREAM
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Deduplicated driver pings with Snowflake-computed H3 res-8 cell'
AS
SELECT
    RECORD_CONTENT:event_id::STRING AS EVENT_ID,
    RECORD_CONTENT:data:driver_id::STRING AS DRIVER_ID,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:event_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EVENT_TS,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:emitted_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EMITTED_TS,
    DATEDIFF('millisecond', EVENT_TS, EMITTED_TS) / 1000 AS LATENESS_S,
    RECORD_CONTENT:data:lat::FLOAT AS LAT,
    RECORD_CONTENT:data:lng::FLOAT AS LNG,
    RECORD_CONTENT:data:zone_id::STRING AS ZONE_ID,
    RECORD_CONTENT:data:status::STRING AS DRIVER_STATUS,
    RECORD_CONTENT:data:order_id::STRING AS ORDER_ID,
    RECORD_CONTENT:data:speed_kmh::FLOAT AS SPEED_KMH,
    RECORD_CONTENT:data:battery_pct::NUMBER AS BATTERY_PCT,
    RECORD_CONTENT:data:h3_r8::STRING AS H3_R8_SOURCE,
    H3_LATLNG_TO_CELL_STRING(LAT, LNG, 8) AS H3_R8,
    H3_R8 = H3_R8_SOURCE AS H3_MATCH,
    RECORD_METADATA:partition::NUMBER AS KAFKA_PARTITION,
    RECORD_METADATA:offset::NUMBER AS KAFKA_OFFSET
FROM ${SNOWFLAKE_DATABASE}.BRONZE.DRIVER_LOCATIONS_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY EVENT_ID
    ORDER BY EMITTED_TS, KAFKA_PARTITION, KAFKA_OFFSET, RECORD_METADATA:file_row::NUMBER
) = 1;

-- Restaurant updates, customer signups and weather, deduplicated (P4 builds dimensions on it).
-- Its own 10-minute lag, not DOWNSTREAM: nothing reads it yet, and a DOWNSTREAM table with no
-- consumers never refreshes at all. Switch to DOWNSTREAM once P4's dimensions depend on it.
CREATE OR REPLACE DYNAMIC TABLE REFERENCE_EVENTS
TARGET_LAG = '10 minutes'
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Deduplicated reference events: RESTAURANT_UPDATED, CUSTOMER_REGISTERED, WEATHER_UPDATED'
AS
SELECT
    RECORD_CONTENT:event_id::STRING AS EVENT_ID,
    RECORD_CONTENT:event_type::STRING AS EVENT_TYPE,
    COALESCE(
        RECORD_CONTENT:data:restaurant_id::STRING,
        RECORD_CONTENT:data:customer_id::STRING,
        RECORD_CONTENT:data:city::STRING
    ) AS ENTITY_ID,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:event_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EVENT_TS,
    TO_TIMESTAMP_NTZ(RECORD_CONTENT:emitted_ts::STRING, 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') AS EMITTED_TS,
    RECORD_CONTENT:data AS PAYLOAD,
    COALESCE(RECORD_METADATA:source::STRING, 'kafka') AS LOAD_SOURCE,
    RECORD_METADATA:partition::NUMBER AS KAFKA_PARTITION,
    RECORD_METADATA:offset::NUMBER AS KAFKA_OFFSET
FROM ${SNOWFLAKE_DATABASE}.BRONZE.REFERENCE_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY EVENT_ID
    ORDER BY EMITTED_TS, KAFKA_PARTITION, KAFKA_OFFSET, RECORD_METADATA:file_row::NUMBER
) = 1;

-- One row per order. Status comes from WHICH events exist (precedence), never from arrival
-- order, so a DELIVERED that arrives before PICKED_UP still gives the right answer.
-- Orders whose ORDER_PLACED has not arrived yet appear with HAS_PLACED = FALSE.
CREATE OR REPLACE DYNAMIC TABLE ORDERS
TARGET_LAG = DOWNSTREAM
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Order lifecycle: one row per order, status by event precedence'
AS
WITH LIFECYCLE AS (
    SELECT
        ORDER_ID,
        MIN(IFF(EVENT_TYPE = 'ORDER_PLACED', EVENT_TS, NULL)) AS PLACED_TS,
        MIN(IFF(EVENT_TYPE = 'ORDER_ACCEPTED', EVENT_TS, NULL)) AS ACCEPTED_TS,
        MIN(IFF(EVENT_TYPE = 'DRIVER_ASSIGNED', EVENT_TS, NULL)) AS DRIVER_ASSIGNED_TS,
        MIN(IFF(EVENT_TYPE = 'FOOD_READY', EVENT_TS, NULL)) AS FOOD_READY_TS,
        MIN(IFF(EVENT_TYPE = 'ORDER_PICKED_UP', EVENT_TS, NULL)) AS PICKED_UP_TS,
        MIN(IFF(EVENT_TYPE = 'ORDER_DELIVERED', EVENT_TS, NULL)) AS DELIVERED_TS,
        MIN(IFF(EVENT_TYPE = 'ORDER_CANCELLED', EVENT_TS, NULL)) AS CANCELLED_TS,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:customer_id::STRING, NULL)) AS CUSTOMER_ID,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:restaurant_id::STRING, NULL)) AS RESTAURANT_ID,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:zone_id::STRING, NULL)) AS ZONE_ID,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:delivery_lat::FLOAT, NULL)) AS DELIVERY_LAT,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:delivery_lng::FLOAT, NULL)) AS DELIVERY_LNG,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', ARRAY_SIZE(PAYLOAD:items), NULL)) AS ITEM_LINES,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:subtotal_inr::NUMBER, NULL)) AS SUBTOTAL_INR,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:delivery_fee_inr::NUMBER, NULL)) AS DELIVERY_FEE_INR,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:surge_fee_inr::NUMBER, NULL)) AS SURGE_FEE_INR,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:discount_inr::NUMBER, NULL)) AS DISCOUNT_INR,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:total_inr::NUMBER, NULL)) AS TOTAL_INR,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:payment_method::STRING, NULL)) AS PAYMENT_METHOD,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:promised_eta_min::NUMBER, NULL)) AS PROMISED_ETA_MIN,
        MAX(IFF(EVENT_TYPE = 'ORDER_PLACED', PAYLOAD:is_raining::BOOLEAN, NULL)) AS IS_RAINING,
        MAX(IFF(EVENT_TYPE = 'ORDER_ACCEPTED', PAYLOAD:estimated_prep_min::NUMBER, NULL)) AS ESTIMATED_PREP_MIN,
        MAX(IFF(EVENT_TYPE = 'DRIVER_ASSIGNED', PAYLOAD:driver_id::STRING, NULL)) AS DRIVER_ID,
        MAX(IFF(EVENT_TYPE = 'DRIVER_ASSIGNED', PAYLOAD:assign_attempts::NUMBER, NULL)) AS ASSIGN_ATTEMPTS,
        MAX(IFF(EVENT_TYPE = 'FOOD_READY', PAYLOAD:actual_prep_min::FLOAT, NULL)) AS ACTUAL_PREP_MIN,
        MAX(IFF(EVENT_TYPE = 'ORDER_DELIVERED', PAYLOAD:actual_delivery_min::FLOAT, NULL)) AS ACTUAL_DELIVERY_MIN,
        MAX(IFF(EVENT_TYPE = 'ORDER_DELIVERED', PAYLOAD:distance_km::FLOAT, NULL)) AS DISTANCE_KM,
        MAX(IFF(EVENT_TYPE = 'ORDER_CANCELLED', PAYLOAD:reason::STRING, NULL)) AS CANCEL_REASON,
        MAX(IFF(EVENT_TYPE = 'ORDER_CANCELLED', PAYLOAD:cancelled_by::STRING, NULL)) AS CANCELLED_BY,
        COUNT(*) AS EVENT_COUNT,
        SUM(IFF(LATENESS_S > 60, 1, 0)) AS LATE_EVENT_COUNT,
        MAX(EMITTED_TS) AS LAST_EMITTED_TS
    FROM ORDER_EVENTS
    GROUP BY ORDER_ID
)

SELECT
    ORDER_ID,
    CASE
        WHEN DELIVERED_TS IS NOT NULL THEN 'DELIVERED'
        WHEN CANCELLED_TS IS NOT NULL THEN 'CANCELLED'
        WHEN PICKED_UP_TS IS NOT NULL THEN 'PICKED_UP'
        WHEN DRIVER_ASSIGNED_TS IS NOT NULL THEN 'DRIVER_ASSIGNED'
        WHEN ACCEPTED_TS IS NOT NULL THEN 'ACCEPTED'
        ELSE 'PLACED'
    END AS ORDER_STATUS,
    PLACED_TS IS NOT NULL AS HAS_PLACED,
    PLACED_TS,
    CONVERT_TIMEZONE('UTC', 'Asia/Kolkata', PLACED_TS) AS PLACED_TS_IST,
    ACCEPTED_TS,
    DRIVER_ASSIGNED_TS,
    FOOD_READY_TS,
    PICKED_UP_TS,
    DELIVERED_TS,
    CANCELLED_TS,
    DATEADD('minute', PROMISED_ETA_MIN, PLACED_TS) AS PROMISED_BY_TS,
    CUSTOMER_ID,
    RESTAURANT_ID,
    ZONE_ID,
    DELIVERY_LAT,
    DELIVERY_LNG,
    H3_LATLNG_TO_CELL_STRING(DELIVERY_LAT, DELIVERY_LNG, 8) AS H3_R8,
    DRIVER_ID,
    ASSIGN_ATTEMPTS,
    ITEM_LINES,
    SUBTOTAL_INR,
    DELIVERY_FEE_INR,
    SURGE_FEE_INR,
    DISCOUNT_INR,
    TOTAL_INR,
    PAYMENT_METHOD,
    IS_RAINING,
    PROMISED_ETA_MIN,
    ESTIMATED_PREP_MIN,
    ACTUAL_PREP_MIN,
    ACTUAL_DELIVERY_MIN,
    DATEDIFF('millisecond', PLACED_TS, DELIVERED_TS) / 60000 AS DELIVERY_MIN_FROM_TS,
    DISTANCE_KM,
    CANCEL_REASON,
    CANCELLED_BY,
    DELIVERED_TS IS NOT NULL AND ACTUAL_DELIVERY_MIN > PROMISED_ETA_MIN AS SLA_BREACHED,
    IFF(DELIVERED_TS IS NOT NULL, ACTUAL_DELIVERY_MIN - PROMISED_ETA_MIN, NULL) AS MINUTES_VS_PROMISE,
    EVENT_COUNT,
    LATE_EVENT_COUNT,
    LAST_EMITTED_TS
FROM LIFECYCLE;
