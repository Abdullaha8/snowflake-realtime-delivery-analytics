-- 06_gold.sql: GOLD real-time aggregates on top of SILVER. Run via `make sf-dt`.
-- TARGET_LAG = '10 minutes' (project default; `make dt-demo` switches to 1 minute).
-- All buckets are in IST because the business runs in Pune.

USE ROLE FOODDEL_TRANSFORM;
USE WAREHOUSE WH_TRANSFORM;
USE SCHEMA ${SNOWFLAKE_DATABASE}.GOLD;

-- Demand vs driver supply per zone and 5-minute bucket -> surge signal.
-- demand = orders placed in the bucket; supply = distinct drivers seen IDLE in the bucket.
-- Surge bands are deliberately simple and explainable:
--   no idle driver but orders waiting -> 2.0x, pressure >= 2 -> 1.75x, >= 1.5 -> 1.5x,
--   >= 1 -> 1.25x, otherwise 1.0x.
CREATE OR REPLACE DYNAMIC TABLE ZONE_DEMAND_SUPPLY_5M
TARGET_LAG = '10 minutes'
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Per zone x 5-minute bucket (IST): orders, idle/online drivers, pressure, surge signal'
AS
WITH DEMAND AS (
    SELECT
        ZONE_ID,
        TIME_SLICE(PLACED_TS_IST, 5, 'MINUTE') AS BUCKET_START_IST,
        COUNT(*) AS ORDERS_PLACED,
        SUM(IFF(IS_RAINING, 1, 0)) AS ORDERS_IN_RAIN
    FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDERS
    WHERE HAS_PLACED
    GROUP BY 1, 2
),

SUPPLY AS (
    SELECT
        ZONE_ID,
        TIME_SLICE(CONVERT_TIMEZONE('UTC', 'Asia/Kolkata', EVENT_TS), 5, 'MINUTE') AS BUCKET_START_IST,
        COUNT(DISTINCT IFF(DRIVER_STATUS != 'OFFLINE', DRIVER_ID, NULL)) AS ONLINE_DRIVERS,
        COUNT(DISTINCT IFF(DRIVER_STATUS = 'IDLE', DRIVER_ID, NULL)) AS IDLE_DRIVERS
    FROM ${SNOWFLAKE_DATABASE}.SILVER.DRIVER_PINGS
    WHERE ZONE_ID IS NOT NULL
    GROUP BY 1, 2
),

JOINED AS (
    SELECT
        COALESCE(D.ZONE_ID, S.ZONE_ID) AS ZONE_ID,
        COALESCE(D.BUCKET_START_IST, S.BUCKET_START_IST) AS BUCKET_START_IST,
        COALESCE(D.ORDERS_PLACED, 0) AS ORDERS_PLACED,
        COALESCE(D.ORDERS_IN_RAIN, 0) AS ORDERS_IN_RAIN,
        COALESCE(S.ONLINE_DRIVERS, 0) AS ONLINE_DRIVERS,
        COALESCE(S.IDLE_DRIVERS, 0) AS IDLE_DRIVERS
    FROM DEMAND AS D
    FULL OUTER JOIN SUPPLY AS S
        ON D.ZONE_ID = S.ZONE_ID AND D.BUCKET_START_IST = S.BUCKET_START_IST
)

SELECT
    ZONE_ID,
    BUCKET_START_IST,
    ORDERS_PLACED,
    ORDERS_IN_RAIN,
    ONLINE_DRIVERS,
    IDLE_DRIVERS,
    ORDERS_PLACED / NULLIF(IDLE_DRIVERS, 0) AS DEMAND_PRESSURE,
    CASE
        WHEN ORDERS_PLACED > 0 AND IDLE_DRIVERS = 0 THEN 2.0
        WHEN ORDERS_PLACED / NULLIF(IDLE_DRIVERS, 0) >= 2 THEN 1.75
        WHEN ORDERS_PLACED / NULLIF(IDLE_DRIVERS, 0) >= 1.5 THEN 1.5
        WHEN ORDERS_PLACED / NULLIF(IDLE_DRIVERS, 0) >= 1 THEN 1.25
        ELSE 1.0
    END AS SURGE_MULTIPLIER
FROM JOINED;

-- Delivered orders that broke their promise, with the context needed to explain why.
CREATE OR REPLACE DYNAMIC TABLE SLA_BREACHES
TARGET_LAG = '10 minutes'
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Delivered orders where actual delivery time exceeded the promised ETA'
AS
SELECT
    ORDER_ID,
    ZONE_ID,
    RESTAURANT_ID,
    DRIVER_ID,
    PLACED_TS_IST,
    HOUR(PLACED_TS_IST) AS PLACED_HOUR_IST,
    IS_RAINING,
    PROMISED_ETA_MIN,
    ACTUAL_DELIVERY_MIN,
    MINUTES_VS_PROMISE AS MINUTES_LATE,
    ESTIMATED_PREP_MIN,
    ACTUAL_PREP_MIN,
    ASSIGN_ATTEMPTS,
    DISTANCE_KM
FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDERS
WHERE SLA_BREACHED;

-- Kitchen performance per restaurant and hour: prep time vs estimate, rejects, cancellations.
CREATE OR REPLACE DYNAMIC TABLE RESTAURANT_PERF_HOURLY
TARGET_LAG = '10 minutes'
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Per restaurant x hour (IST): orders, prep time vs estimate, reject and cancel rates'
AS
SELECT
    RESTAURANT_ID,
    DATE_TRUNC('hour', PLACED_TS_IST) AS HOUR_START_IST,
    COUNT(*) AS ORDERS_PLACED,
    SUM(IFF(ACCEPTED_TS IS NOT NULL, 1, 0)) AS ORDERS_ACCEPTED,
    SUM(IFF(CANCEL_REASON IN ('RESTAURANT_REJECTED', 'ITEM_UNAVAILABLE'), 1, 0)) AS RESTAURANT_REJECTS,
    SUM(IFF(ORDER_STATUS = 'CANCELLED', 1, 0)) AS ORDERS_CANCELLED,
    SUM(IFF(ORDER_STATUS = 'DELIVERED', 1, 0)) AS ORDERS_DELIVERED,
    AVG(ESTIMATED_PREP_MIN) AS AVG_ESTIMATED_PREP_MIN,
    AVG(ACTUAL_PREP_MIN) AS AVG_ACTUAL_PREP_MIN,
    APPROX_PERCENTILE(ACTUAL_PREP_MIN, 0.9) AS P90_ACTUAL_PREP_MIN,
    AVG(ACTUAL_PREP_MIN - ESTIMATED_PREP_MIN) AS AVG_PREP_DELAY_MIN,
    SUM(IFF(SLA_BREACHED, 1, 0)) AS SLA_BREACHES
FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDERS
WHERE HAS_PLACED
GROUP BY 1, 2;

-- Demand heatmap per H3 res-8 cell (computed in Snowflake) and hour, for the Streamlit map.
CREATE OR REPLACE DYNAMIC TABLE HEX_DEMAND_HOURLY
TARGET_LAG = '10 minutes'
WAREHOUSE = WH_TRANSFORM
REFRESH_MODE = INCREMENTAL
INITIALIZE = ON_CREATE
COMMENT = 'Per H3 res-8 cell x hour (IST): orders, delivered, avg delivery time, SLA breaches'
AS
SELECT
    H3_R8,
    ZONE_ID,
    DATE_TRUNC('hour', PLACED_TS_IST) AS HOUR_START_IST,
    COUNT(*) AS ORDERS_PLACED,
    SUM(IFF(ORDER_STATUS = 'DELIVERED', 1, 0)) AS ORDERS_DELIVERED,
    AVG(ACTUAL_DELIVERY_MIN) AS AVG_DELIVERY_MIN,
    SUM(IFF(SLA_BREACHED, 1, 0)) AS SLA_BREACHES,
    SUM(TOTAL_INR) AS GMV_PLACED_INR
FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDERS
WHERE HAS_PLACED
GROUP BY 1, 2, 3;

-- Open orders already past their promised time. A view, not a Dynamic Table: "now" changes
-- every second, and a time-relative filter cannot be maintained incrementally.
-- "Now" is STREAM time (the newest event seen), not the wall clock, because simulated runs
-- replay accelerated or past time. In production this would be CURRENT_TIMESTAMP().
CREATE OR REPLACE VIEW V_ORDERS_AT_RISK
COMMENT = 'Open orders past their promised delivery time, as of the latest event seen'
AS
WITH STREAM_CLOCK AS (
    SELECT MAX(EVENT_TS) AS STREAM_NOW
    FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDER_EVENTS
)

SELECT
    O.ORDER_ID,
    O.ORDER_STATUS,
    O.ZONE_ID,
    O.RESTAURANT_ID,
    O.DRIVER_ID,
    O.PLACED_TS,
    O.PROMISED_BY_TS,
    C.STREAM_NOW,
    DATEDIFF('second', O.PROMISED_BY_TS, C.STREAM_NOW) / 60 AS MINUTES_OVERDUE
FROM ${SNOWFLAKE_DATABASE}.SILVER.ORDERS AS O
CROSS JOIN STREAM_CLOCK AS C
WHERE
    O.HAS_PLACED
    AND O.ORDER_STATUS NOT IN ('DELIVERED', 'CANCELLED')
    AND O.PROMISED_BY_TS < C.STREAM_NOW;
