-- 08b_alert_email.sql: email notification integration (ACCOUNTADMIN). Run by
-- `make alerts-setup` only when SNOWFLAKE_ALERT_EMAIL is set. Snowflake only delivers to
-- addresses verified in a user's Snowsight profile.

USE ROLE ACCOUNTADMIN;

CREATE NOTIFICATION INTEGRATION IF NOT EXISTS FOODDEL_EMAIL
TYPE = EMAIL
ENABLED = TRUE
ALLOWED_RECIPIENTS = ('${SNOWFLAKE_ALERT_EMAIL}')
COMMENT = 'fooddel alert emails';

ALTER NOTIFICATION INTEGRATION FOODDEL_EMAIL SET ALLOWED_RECIPIENTS = ('${SNOWFLAKE_ALERT_EMAIL}');

GRANT USAGE ON INTEGRATION FOODDEL_EMAIL TO ROLE FOODDEL_TRANSFORM;
