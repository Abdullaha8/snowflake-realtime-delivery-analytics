-- 10_governance.sql: roles and row-level-security mapping for the secure-view governance
-- layer. Run via `make sf-governance`, BEFORE `make dbt` (dbt builds the secure views).
--
-- This account is Snowflake STANDARD edition: masking policies and row access policies
-- (Enterprise) are unavailable ("Unsupported feature"). The same guarantees are implemented
-- with SECURE VIEWS in MARTS_SECURE (dbt models/secure): PII masked by role, rows filtered by
-- zone through GOVERNANCE.ZONE_ACCESS. Consumers (BI, zone managers, PII readers) get NO
-- direct access to MARTS tables, only to the views.

-- 1. Roles ---------------------------------------------------------------------------------
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS FOODDEL_PII_READER COMMENT = 'Support/fraud: all rows, unmasked PII';
CREATE ROLE IF NOT EXISTS FOODDEL_OPS_WEST COMMENT = 'Zone manager west: own zones only, PII masked';
CREATE ROLE IF NOT EXISTS FOODDEL_OPS_EAST COMMENT = 'Zone manager east: own zones only, PII masked';

USE ROLE SECURITYADMIN;
GRANT ROLE FOODDEL_PII_READER TO ROLE SYSADMIN;
GRANT ROLE FOODDEL_OPS_WEST TO ROLE SYSADMIN;
GRANT ROLE FOODDEL_OPS_EAST TO ROLE SYSADMIN;
-- PII readers can do everything BI can (all zones), plus clear-text PII.
GRANT ROLE FOODDEL_BI TO ROLE FOODDEL_PII_READER;
-- Demo: the admin user holds every role and switches with USE ROLE (no extra human users).
GRANT ROLE FOODDEL_PII_READER TO USER ${SNOWFLAKE_ADMIN_USER};
GRANT ROLE FOODDEL_OPS_WEST TO USER ${SNOWFLAKE_ADMIN_USER};
GRANT ROLE FOODDEL_OPS_EAST TO USER ${SNOWFLAKE_ADMIN_USER};

-- Consumers: the secure-view schema and the BI warehouse only. (SELECT on the views themselves
-- is granted by dbt's `grants` config on every build.)
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_OPS_WEST;
GRANT USAGE ON DATABASE ${SNOWFLAKE_DATABASE} TO ROLE FOODDEL_OPS_EAST;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS_SECURE TO ROLE FOODDEL_BI;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS_SECURE TO ROLE FOODDEL_OPS_WEST;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS_SECURE TO ROLE FOODDEL_OPS_EAST;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE FOODDEL_OPS_WEST;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE FOODDEL_OPS_EAST;

-- dbt (TRANSFORM) builds the secure views and reads the zone mapping inside them.
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS_SECURE TO ROLE FOODDEL_TRANSFORM;
GRANT CREATE VIEW ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS_SECURE TO ROLE FOODDEL_TRANSFORM;
GRANT USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.GOVERNANCE TO ROLE FOODDEL_TRANSFORM;

-- Consumers must not read MARTS tables directly (BI had P4 future grants). Idempotent.
REVOKE SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_BI;
REVOKE SELECT ON FUTURE VIEWS IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_BI;
REVOKE SELECT ON ALL TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_BI;
REVOKE USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_BI;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_WEST;
REVOKE SELECT ON ALL TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_WEST;
REVOKE USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_WEST;
REVOKE SELECT ON FUTURE TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_EAST;
REVOKE SELECT ON ALL TABLES IN SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_EAST;
REVOKE USAGE ON SCHEMA ${SNOWFLAKE_DATABASE}.MARTS FROM ROLE FOODDEL_OPS_EAST;

-- 2. Zone access mapping: which role may see which zone. Giving a manager a new zone is an
--    INSERT here, not a code change. Owned by SYSADMIN; TRANSFORM can only read it.
USE ROLE SYSADMIN;
USE WAREHOUSE WH_TRANSFORM;
USE SCHEMA ${SNOWFLAKE_DATABASE}.GOVERNANCE;

CREATE TABLE IF NOT EXISTS ZONE_ACCESS (
    ROLE_NAME STRING NOT NULL,
    ZONE_ID STRING NOT NULL
)
COMMENT = 'Row-level security mapping used by MARTS_SECURE views (role -> zone)';
GRANT SELECT ON TABLE ZONE_ACCESS TO ROLE FOODDEL_TRANSFORM;

MERGE INTO ZONE_ACCESS AS T
USING (
    SELECT
        COLUMN1 AS ROLE_NAME,
        COLUMN2 AS ZONE_ID
    FROM
        VALUES
        ('FOODDEL_OPS_WEST', 'HINJEWADI'), ('FOODDEL_OPS_WEST', 'WAKAD'),
        ('FOODDEL_OPS_WEST', 'BANER'), ('FOODDEL_OPS_WEST', 'AUNDH'),
        ('FOODDEL_OPS_WEST', 'KOTHRUD'), ('FOODDEL_OPS_WEST', 'SHIVAJINAGAR'),
        ('FOODDEL_OPS_EAST', 'CAMP'), ('FOODDEL_OPS_EAST', 'KOREGAON_PARK'),
        ('FOODDEL_OPS_EAST', 'KALYANI_NAGAR'), ('FOODDEL_OPS_EAST', 'VIMAN_NAGAR'),
        ('FOODDEL_OPS_EAST', 'MAGARPATTA'), ('FOODDEL_OPS_EAST', 'HADAPSAR')
) AS S
    ON T.ROLE_NAME = S.ROLE_NAME AND T.ZONE_ID = S.ZONE_ID
WHEN NOT MATCHED THEN INSERT (ROLE_NAME, ZONE_ID) VALUES (S.ROLE_NAME, S.ZONE_ID);
