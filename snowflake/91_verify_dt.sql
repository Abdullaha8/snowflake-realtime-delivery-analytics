-- 91_verify_dt.sql: are the Dynamic Tables healthy and is SILVER/GOLD correct?
-- Run with `make sf-verify-dt` (uses WH_TRANSFORM for a few seconds).

USE ROLE FOODDEL_TRANSFORM;
USE WAREHOUSE WH_TRANSFORM;
USE DATABASE ${SNOWFLAKE_DATABASE};

-- 1. Health (ACTIVE, INCREMENTAL, lags) is checked by `make dt-status` (SHOW DYNAMIC TABLES).

-- 2. Data quality. Every check should be 0. (While a run is still streaming, open orders can
--    legitimately be missing later events; run after the stream has drained.)
SELECT
    'duplicate event_id in SILVER.ORDER_EVENTS' AS CHECK_NAME,
    COUNT(*) - COUNT(DISTINCT EVENT_ID) AS FAILURES
FROM SILVER.ORDER_EVENTS
UNION ALL
SELECT
    'duplicate event_id in SILVER.DRIVER_PINGS' AS CHECK_NAME,
    COUNT(*) - COUNT(DISTINCT EVENT_ID) AS FAILURES
FROM SILVER.DRIVER_PINGS
UNION ALL
SELECT
    'orders without ORDER_PLACED' AS CHECK_NAME,
    COUNT_IF(NOT HAS_PLACED) AS FAILURES
FROM SILVER.ORDERS
UNION ALL
SELECT
    'delivered without pickup' AS CHECK_NAME,
    COUNT_IF(DELIVERED_TS IS NOT NULL AND PICKED_UP_TS IS NULL) AS FAILURES
FROM SILVER.ORDERS
UNION ALL
SELECT
    'picked up without food ready or driver' AS CHECK_NAME,
    COUNT_IF(PICKED_UP_TS IS NOT NULL AND (FOOD_READY_TS IS NULL OR DRIVER_ASSIGNED_TS IS NULL)) AS FAILURES
FROM SILVER.ORDERS
UNION ALL
SELECT
    'cancelled after pickup' AS CHECK_NAME,
    COUNT_IF(CANCELLED_TS IS NOT NULL AND PICKED_UP_TS IS NOT NULL) AS FAILURES
FROM SILVER.ORDERS
UNION ALL
SELECT
    'delivery minutes payload vs timestamps differ > 0.1' AS CHECK_NAME,
    COUNT_IF(ABS(ACTUAL_DELIVERY_MIN - DELIVERY_MIN_FROM_TS) > 0.1) AS FAILURES
FROM SILVER.ORDERS
UNION ALL
SELECT
    'H3 cell mismatch (Snowflake vs simulator)' AS CHECK_NAME,
    COUNT_IF(NOT H3_MATCH) AS FAILURES
FROM SILVER.DRIVER_PINGS;

-- 3. Headline numbers.
SELECT
    COUNT(*) AS ORDERS,
    COUNT_IF(ORDER_STATUS = 'DELIVERED') AS DELIVERED,
    COUNT_IF(ORDER_STATUS = 'CANCELLED') AS CANCELLED,
    ROUND(100 * COUNT_IF(SLA_BREACHED) / NULLIF(COUNT_IF(ORDER_STATUS = 'DELIVERED'), 0), 2) AS SLA_BREACH_PCT,
    ROUND(AVG(ACTUAL_DELIVERY_MIN), 1) AS AVG_DELIVERY_MIN,
    SUM(IFF(ORDER_STATUS = 'DELIVERED', TOTAL_INR, 0)) AS GMV_INR
FROM SILVER.ORDERS
WHERE HAS_PLACED;

-- 4. Surge: the zones and 5-minute buckets under the most pressure.
SELECT
    ZONE_ID,
    BUCKET_START_IST,
    ORDERS_PLACED,
    IDLE_DRIVERS,
    ONLINE_DRIVERS,
    SURGE_MULTIPLIER
FROM GOLD.ZONE_DEMAND_SUPPLY_5M
ORDER BY SURGE_MULTIPLIER DESC, ORDERS_PLACED DESC
LIMIT 10;

-- 5. Orders at risk right now (stream time).
SELECT
    COUNT(*) AS OPEN_ORDERS_PAST_PROMISE,
    MAX(MINUTES_OVERDUE) AS WORST_MINUTES_OVERDUE
FROM GOLD.V_ORDERS_AT_RISK;
